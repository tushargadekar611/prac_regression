import pandas as pd
import numpy as np
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
from sklearn.linear_model import LinearRegression
import numpy as np

df=pd.DataFrame({
    'sh':[1,2,3,4,5],
    'mk':[3,6,11,18,27]
})
poly=PolynomialFeatures(degree=2)
X_poly=poly.fit_transform(df[['sh']])
m=df['mk']

mod=LinearRegression()
mod.fit(X_poly,m)

pr=mod.predict(poly.transform([[6]]))
print(pr)